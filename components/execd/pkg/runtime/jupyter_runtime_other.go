package runtime

import (
	"errors"
	"os"
)

func openRuntimeFileNoFollow(filePath string) (*os.File, error) {
	info, err := os.Lstat(filePath)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, errors.New("not a regular file")
	}
	return os.Open(filePath)
}

func runtimeFileOwnerUID(os.FileInfo) (int, bool) {
	return 0, false
}
