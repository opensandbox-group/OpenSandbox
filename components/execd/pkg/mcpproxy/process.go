package mcpproxy

import (
	"os/exec"
	"syscall"
)

// setProcAttr configures the subprocess to run in its own process group
// so Close() can kill the entire tree.
func setProcAttr(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
}

// forceKillProcess kills the subprocess and its process group.
func forceKillProcess(cmd *exec.Cmd) {
	pgid, err := syscall.Getpgid(cmd.Process.Pid)
	if err == nil {
		_ = syscall.Kill(-pgid, syscall.SIGKILL)
	} else {
		_ = cmd.Process.Kill()
	}
}
