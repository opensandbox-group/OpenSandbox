//go:build windows

package controller

import (
	"os"

	"golang.org/x/sys/windows"
)

// openUploadStagingFile creates the staging file with FILE_SHARE_DELETE so the
// pinned handle can stay open through the rename. os.OpenFile omits that share
// mode, and Windows rejects renaming a file held open without it.
func openUploadStagingFile(name string, _ os.FileMode) (*os.File, error) {
	path, err := windows.UTF16PtrFromString(name)
	if err != nil {
		return nil, err
	}
	handle, err := windows.CreateFile(
		path,
		windows.GENERIC_READ|windows.GENERIC_WRITE,
		windows.FILE_SHARE_READ|windows.FILE_SHARE_WRITE|windows.FILE_SHARE_DELETE,
		nil,
		windows.CREATE_NEW,
		windows.FILE_ATTRIBUTE_NORMAL,
		0,
	)
	if err != nil {
		return nil, err
	}
	file := os.NewFile(uintptr(handle), name)
	if file == nil {
		_ = windows.CloseHandle(handle)
		return nil, windows.ERROR_INVALID_HANDLE
	}
	return file, nil
}
